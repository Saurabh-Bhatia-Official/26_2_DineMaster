CREATE TABLE IF NOT EXISTS app_seed_state (
    seed_key VARCHAR(100) PRIMARY KEY,
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_branches (
    user_id BIGINT NOT NULL,
    branch_id BIGINT NOT NULL,
    assignment_verified BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (user_id, branch_id)
);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS staff_sync_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    payload TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    branch_id BIGINT,
    user_id BIGINT,
    role_code VARCHAR(50),
    type VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    body TEXT NOT NULL,
    ref_type VARCHAR(50),
    ref_id BIGINT,
    read_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    branch_id BIGINT,
    setting_key VARCHAR(100) NOT NULL,
    value_json TEXT NOT NULL,
    version INTEGER NOT NULL DEFAULT 1,
    updated_by BIGINT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_settings_branch_key ON settings(tenant_id, branch_id, setting_key);
CREATE TABLE IF NOT EXISTS setting_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    branch_id BIGINT,
    setting_key VARCHAR(100) NOT NULL,
    old_value_json TEXT,
    new_value_json TEXT NOT NULL,
    changed_by BIGINT NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE SCHEMA IF NOT EXISTS ops;
CREATE TABLE IF NOT EXISTS ops.sync_identity_map (
    entity_type VARCHAR(60) NOT NULL,
    sync_id UUID NOT NULL,
    edge_id BIGINT,
    cloud_id BIGINT,
    mapping_status VARCHAR(24) NOT NULL DEFAULT 'UNRECONCILED',
    resolution_note TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (entity_type, sync_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_sync_identity_map_edge
    ON ops.sync_identity_map(entity_type, edge_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_sync_identity_map_cloud
    ON ops.sync_identity_map(entity_type, cloud_id);

CREATE TABLE IF NOT EXISTS payment_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sync_id UUID NOT NULL UNIQUE,
    order_id BIGINT NOT NULL,
    tenant_id BIGINT NOT NULL,
    branch_id BIGINT NOT NULL,
    event_type VARCHAR(16) NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    currency CHAR(3) NOT NULL,
    payment_method VARCHAR(50),
    idempotency_key VARCHAR(100) NOT NULL,
    reverses_event_id UUID,
    source_device_id UUID,
    actor_user_id BIGINT,
    external_reference VARCHAR(150),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_test_payment_idempotency UNIQUE (tenant_id, idempotency_key)
);
