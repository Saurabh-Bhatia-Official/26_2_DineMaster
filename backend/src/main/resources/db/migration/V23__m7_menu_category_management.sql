ALTER TABLE products ADD COLUMN category_id BIGINT REFERENCES categories(id) ON DELETE RESTRICT;
UPDATE products p SET category_id = c.id
FROM restaurants r, categories c
WHERE p.restaurant_id = r.id AND c.tenant_id = r.tenant_id
  AND LOWER(c.name) = LOWER(p.category);
CREATE INDEX idx_products_category_id ON products(category_id);

CREATE TABLE branch_products (
    branch_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    price_override NUMERIC(12,2) CHECK (price_override IS NULL OR price_override >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (branch_id, product_id)
);
CREATE INDEX idx_branch_products_product ON branch_products(product_id);

CREATE TABLE menu_price_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    old_price NUMERIC(12,2),
    new_price NUMERIC(12,2),
    changed_by VARCHAR(150) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
