ALTER TABLE recipes RENAME TO recipe_legacy_lines;

CREATE TABLE recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    version INTEGER NOT NULL CHECK (version > 0),
    steps TEXT NOT NULL DEFAULT '[]',
    prep_min INTEGER CHECK (prep_min IS NULL OR prep_min >= 0),
    cook_min INTEGER CHECK (cook_min IS NULL OR cook_min >= 0),
    portion NUMERIC(12,3) CHECK (portion IS NULL OR portion > 0),
    difficulty VARCHAR(30),
    video_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (product_id, version)
);
CREATE UNIQUE INDEX uq_recipes_one_active_product ON recipes(product_id) WHERE is_active;

CREATE TABLE recipe_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL REFERENCES recipes(id) ON DELETE RESTRICT,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    ingredient_id BIGINT NOT NULL REFERENCES inventory(id) ON DELETE RESTRICT,
    quantity NUMERIC(14,4) NOT NULL CHECK (quantity > 0),
    unit VARCHAR(30) NOT NULL,
    UNIQUE (recipe_id, ingredient_id)
);
CREATE INDEX idx_recipe_items_product ON recipe_items(product_id, recipe_id);
CREATE INDEX idx_recipe_items_ingredient ON recipe_items(ingredient_id);

INSERT INTO recipes(product_id, version, is_active)
SELECT DISTINCT product_id, 1, TRUE FROM recipe_legacy_lines;
INSERT INTO recipe_items(recipe_id, tenant_id, product_id, ingredient_id, quantity, unit)
SELECT r.id, p.tenant_id, legacy.product_id, legacy.ingredient_id, legacy.quantity_used, i.unit
FROM recipe_legacy_lines legacy
JOIN recipes r ON r.product_id = legacy.product_id AND r.version = 1
JOIN products p ON p.id = legacy.product_id
JOIN inventory i ON i.id = legacy.ingredient_id;
DROP TABLE recipe_legacy_lines;

ALTER TABLE inventory ADD COLUMN unit_cost NUMERIC(12,4) NOT NULL DEFAULT 0 CHECK (unit_cost >= 0);
CREATE TABLE stock_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_id BIGINT NOT NULL REFERENCES inventory(id) ON DELETE RESTRICT,
    quantity_on_hand NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (quantity_on_hand >= 0),
    expiry_date DATE,
    unit_cost NUMERIC(12,4) NOT NULL DEFAULT 0 CHECK (unit_cost >= 0),
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO stock_batches(inventory_id, quantity_on_hand, expiry_date, unit_cost)
SELECT id, current_stock, expiry_date, unit_cost FROM inventory WHERE current_stock > 0;
CREATE INDEX idx_stock_batches_fefo ON stock_batches(inventory_id, expiry_date ASC NULLS LAST, received_at ASC);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_id BIGINT NOT NULL REFERENCES inventory(id) ON DELETE RESTRICT,
    batch_id BIGINT REFERENCES stock_batches(id) ON DELETE RESTRICT,
    delta NUMERIC(14,4) NOT NULL,
    reason VARCHAR(20) NOT NULL CHECK (reason IN ('PURCHASE','SALE','ADJUSTMENT','COUNT','VOID_WASTE')),
    ref_type VARCHAR(30),
    ref_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_stock_movements_inventory ON stock_movements(inventory_id, created_at DESC);

CREATE TABLE recipe_deduction_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED','PROCESSING','COMPLETED','FAILED')),
    attempts INTEGER NOT NULL DEFAULT 0,
    error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_recipe_deduction_jobs_queue ON recipe_deduction_jobs(status, created_at);
CREATE TABLE order_recipe_snapshots (
    order_item_id BIGINT PRIMARY KEY REFERENCES order_items(id) ON DELETE RESTRICT,
    recipe_id BIGINT REFERENCES recipes(id) ON DELETE RESTRICT
);
CREATE TABLE processed_events (
    event_key VARCHAR(120) PRIMARY KEY,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
