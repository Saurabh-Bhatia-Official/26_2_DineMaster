CREATE TABLE kitchen_event_counters (
    branch_id BIGINT PRIMARY KEY REFERENCES restaurants(id) ON DELETE CASCADE,
    last_seq BIGINT NOT NULL DEFAULT 0 CHECK (last_seq >= 0)
);

CREATE TABLE kitchen_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    sequence BIGINT NOT NULL,
    station_key VARCHAR(100),
    event_type VARCHAR(60) NOT NULL,
    payload JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(branch_id, sequence)
);
CREATE INDEX ix_kitchen_events_replay ON kitchen_events(branch_id, sequence);

CREATE TABLE kitchen_delays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kot_id BIGINT NOT NULL REFERENCES kot(id) ON DELETE RESTRICT,
    reason TEXT NOT NULL,
    minutes INTEGER NOT NULL CHECK (minutes > 0),
    recorded_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_kitchen_delays_kot ON kitchen_delays(kot_id, created_at);
ALTER TABLE kot ADD COLUMN assigned_chef_id BIGINT REFERENCES users(id);

INSERT INTO kot_items(kot_id, order_item_id, product_id, item_name_snapshot, quantity, instructions_snapshot)
SELECT oi.kot_id, oi.id, oi.product_id, COALESCE(oi.product_name_snapshot, p.name), oi.quantity, oi.notes
FROM order_items oi
JOIN products p ON p.id = oi.product_id
WHERE oi.kot_id IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM kot_items ki WHERE ki.order_item_id = oi.id);
