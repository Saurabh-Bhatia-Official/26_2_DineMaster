CREATE TABLE waiter_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    table_id BIGINT NOT NULL REFERENCES tables(id) ON DELETE RESTRICT,
    waiter_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    released_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_waiter_assignment_active_table ON waiter_assignments(table_id) WHERE released_at IS NULL;
CREATE INDEX ix_waiter_assignment_current ON waiter_assignments(branch_id, waiter_id, released_at, table_id);
INSERT INTO waiter_assignments(branch_id, table_id, waiter_id)
SELECT t.restaurant_id, t.id, t.waiter_id FROM tables t WHERE t.waiter_id IS NOT NULL;

CREATE TABLE table_status_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id BIGINT NOT NULL REFERENCES tables(id) ON DELETE RESTRICT,
    from_status VARCHAR(30),
    to_status VARCHAR(30) NOT NULL,
    actor_id BIGINT REFERENCES users(id),
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_table_status_logs_history ON table_status_logs(table_id, created_at, id);
