SELECT DISTINCT p.tenant_id, 'GST ' || TRIM(TO_CHAR(p.gst_percentage, 'FM990D00')) || '%', p.gst_percentage
FROM products p
ON CONFLICT (tenant_id, rate_percent) DO NOTHING;
