CROSS JOIN (VALUES ('GST 0%', 0.00), ('GST 5%', 5.00), ('GST 12%', 12.00), ('GST 18%', 18.00)) defaults(name, rate)
ON CONFLICT (tenant_id, rate_percent) DO NOTHING;
