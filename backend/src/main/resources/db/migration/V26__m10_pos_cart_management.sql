UPDATE orders o SET subtotal = COALESCE(lines.subtotal, 0), tax_amount = COALESCE(lines.tax, 0)
FROM (SELECT oi.order_id, SUM(oi.price * oi.quantity) subtotal,
             SUM(oi.price * oi.quantity * COALESCE(p.gst_percentage, 0) / 100) tax
      FROM order_items oi JOIN products p ON p.id = oi.product_id
      WHERE UPPER(oi.status) <> 'CANCELLED' GROUP BY oi.order_id) lines
WHERE lines.order_id = o.id;
UPDATE order_items oi SET tax_rate_snapshot = COALESCE(p.gst_percentage, 0)
FROM products p WHERE p.id = oi.product_id;
