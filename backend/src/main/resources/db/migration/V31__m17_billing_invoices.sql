CREATE TABLE invoice_counters (
    branch_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    financial_year VARCHAR(5) NOT NULL,
    last_value INTEGER NOT NULL CHECK (last_value > 0),
    PRIMARY KEY (branch_id, financial_year)
);

CREATE TABLE invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id),
    branch_id BIGINT NOT NULL REFERENCES restaurants(id),
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE RESTRICT,
    invoice_no VARCHAR(40) NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    tax_amount NUMERIC(12,2) NOT NULL CHECK (tax_amount >= 0),
    discount_amount NUMERIC(12,2) NOT NULL CHECK (discount_amount >= 0),
    total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
    UNIQUE (branch_id, invoice_no)
);

CREATE INDEX ix_invoices_branch_issued_at ON invoices(branch_id, issued_at DESC);
