CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    branch_id BIGINT REFERENCES restaurants(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    role_code VARCHAR(50),
    type VARCHAR(50) NOT NULL,
    title VARCHAR(200) NOT NULL,
    body TEXT NOT NULL,
    ref_type VARCHAR(50),
    ref_id BIGINT,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_notifications_recipient CHECK (user_id IS NOT NULL OR role_code IS NOT NULL)
);

CREATE INDEX ix_notifications_user_inbox ON notifications(tenant_id, user_id, created_at DESC);
CREATE INDEX ix_notifications_role_inbox ON notifications(tenant_id, role_code, branch_id, created_at DESC);
